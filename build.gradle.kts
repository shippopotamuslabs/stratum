    val screenshotTestTaskNames =
        setOf(
            "updateDebugScreenshotTest",
            "validateDebugScreenshotTest",
            "updateReleaseScreenshotTest",
            "validateReleaseScreenshotTest",
        )

    // Centralized screenshot-test wiring (STR-11): covered modules opt in with the one-line
    // `alias(libs.plugins.screenshot)`; the experimental flag and test dependencies come from
