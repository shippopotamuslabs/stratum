package com.stratum.domain.workout

import com.stratum.domain.program.SetType
import com.stratum.domain.workout.myorep.MyoMatchStructure

/**
 * Ordinal geometry + cluster-anchor resolution for a straight-set block, extracted
 * from [StraightSetRecommendationPolicy]: which logged set capacities the block
 * (the performance anchor) and how many fatigue steps separate the anchor from a
 * target set.
 */

/** Minimal [SetSlot] projection so geometry shares [MyoMatchStructure] with live/edit. */
fun RenderedSet.toStructureSlot(): SetSlot =
    SetSlot(
        slotId = slotId,
        workoutLiftId = workoutLiftId,
        liftId = liftId,
        position = position,
        setType = setType,
        isTopSet = isTopSet,
        repMin = repMin,
        repMax = repMax,
        rirGoal = rirGoal,
        restSeconds = restSeconds,
        myoRepKind = myoRepKind,
    )

/** True for auto-generated myo minis (overlay slots minted with a `mini-` id). */
fun RenderedSet.isAutoGeneratedMyoMini(): Boolean {
    if (setType != SetType.MyoRep) return false
    val overlayId = slotId as? SetSlotId.Overlay ?: return false
    return overlayId.instanceId.value.startsWith("mini-")
}

/**
 * STR-232: when the just-logged set is a mini of a rep-match cluster, the next
 * working set's gradient must root at the match activation (the top set), not at
 * the backoff the minis hang under. The backoff plus its minis are one cluster
 * whose whole job is matching the activation's reps; the backoff's shortfall —
 * finished off by 0-RIR minis — understates capacity exactly like a mini does,
 * and the next match working set takes full normal rest before it. Returns the
 * activation when the last performed set is a match mini whose activation is
 * logged; null otherwise. RepFloor clusters are deliberately not matched here:
 * their minis parent to the activation itself, so the normal anchor already is
 * the top set, and following standards keep counting cluster volume (the
 * POST-MYO-STRAIGHT doctrine).
 */
fun resolveMatchClusterActivation(
    setsByPosition: List<RenderedSet>,
    lastPerformedSet: RenderedSet,
): RenderedSet? {
    if (!lastPerformedSet.isAutoGeneratedMyoMini()) return null
    val slots = setsByPosition.map { it.toStructureSlot() }
    val activation =
        MyoMatchStructure.resolveMatchActivation(slots, lastPerformedSet.toStructureSlot())
            ?: return null
    val activationSet =
        setsByPosition.firstOrNull { it.slotId == activation.slotId } ?: return null
    return activationSet.takeIf { it.loggedValue != null }
}

fun fatigueSetIndex(performanceOrdinal: Int, targetOrdinal: Int): Int =
    (targetOrdinal - performanceOrdinal + 1).coerceAtLeast(1)

/**
 * Fatigue story index of [targetOrdinal] when the anchor at [performanceOrdinal]
 * is set 1. With [skipMinisInFatigueIndex] (the STR-232 match-cluster anchor),
 * auto-generated minis between the anchor and the target consume no steps — the
 * backoff and its completed cluster count as the one normal set they replace —
 * while every other set (working sets, drops) still counts as before.
 */
fun fatigueSetIndex(
    setsByPosition: List<RenderedSet>,
    performanceOrdinal: Int,
    targetOrdinal: Int,
    skipMinisInFatigueIndex: Boolean,
): Int {
    if (!skipMinisInFatigueIndex || performanceOrdinal !in setsByPosition.indices) {
        return fatigueSetIndex(performanceOrdinal, targetOrdinal)
    }
    val to = targetOrdinal.coerceAtMost(setsByPosition.lastIndex)
    if (to <= performanceOrdinal) return 1
    val workingSteps =
        (performanceOrdinal + 1..to).count { index -> !setsByPosition[index].isAutoGeneratedMyoMini() }
    return (workingSteps + 1).coerceAtLeast(1)
}

fun remainingCountAfterPerformanceAnchor(
    setsByPosition: List<RenderedSet>,
    performanceOrdinal: Int,
    lastUpcomingOrdinal: Int,
    skipMinisInFatigueIndex: Boolean = false,
): Int =
    (
        fatigueSetIndex(
            setsByPosition,
            performanceOrdinal,
            lastUpcomingOrdinal,
            skipMinisInFatigueIndex,
        ) - 1
        ).coerceAtLeast(0)
