package com.stratum.domain.workout

import com.stratum.domain.program.SetType
import com.stratum.domain.workout.myorep.MyoMatchStructure

/**
 * Ordinal geometry + cluster-anchor resolution for a straight-set block, extracted
 * from [StraightSetRecommendationPolicy]: which logged set capacities the block
 * (the performance anchor) and how many fatigue steps separate the anchor from a
 * target set.
 */

/** Minimal [SetSlot] projection so geometry shares [MyoMatchStructure] with live/edit. */
fun RenderedSet.toStructureSlot(): SetSlot =
    SetSlot(
        slotId = slotId,
        workoutLiftId = workoutLiftId,
        liftId = liftId,
        position = position,
        setType = setType,
        isTopSet = isTopSet,
        repMin = repMin,
        repMax = repMax,
        rirGoal = rirGoal,
        restSeconds = restSeconds,
        myoRepKind = myoRepKind,
    )

/** True for auto-generated myo minis (overlay slots minted with a `mini-` id). */
fun RenderedSet.isAutoGeneratedMyoMini(): Boolean {
    if (setType != SetType.MyoRep) return false
    val overlayId = slotId as? SetSlotId.Overlay ?: return false
    return overlayId.instanceId.value.startsWith("mini-")
}

/**
 * STR-232: when the just-logged set is a mini of a rep-match cluster, the next
 * working set's gradient must root at the match activation (the top set), not at
 * the backoff the minis hang under. The backoff plus its minis are one cluster
 * whose whole job is matching the activation's reps; the backoff's shortfall —
 * finished off by 0-RIR minis — understates capacity exactly like a mini does,
 * and the next match working set takes full normal rest before it. Returns the
 * activation when the last performed set is a match mini whose activation is
 * logged; null otherwise. RepFloor clusters are deliberately not matched here:
 * their minis parent to the activation itself, so the normal anchor already is
 * the top set, and following standards keep counting cluster volume (the
 * POST-MYO-STRAIGHT doctrine).
 */
fun resolveMatchClusterActivation(
    setsByPosition: List<RenderedSet>,
    lastPerformedSet: RenderedSet,
): RenderedSet? {
    if (!lastPerformedSet.isAutoGeneratedMyoMini()) return null
    val slots = setsByPosition.map { it.toStructureSlot() }
    val activation =
        MyoMatchStructure.resolveMatchActivation(slots, lastPerformedSet.toStructureSlot())
            ?: return null
    val activationSet =
        setsByPosition.firstOrNull { it.slotId == activation.slotId } ?: return null
    return activationSet.takeIf { it.loggedValue != null }
}

fun fatigueSetIndex(performanceOrdinal: Int, targetOrdinal: Int): Int =
    (targetOrdinal - performanceOrdinal + 1).coerceAtLeast(1)

/**
 * Fatigue story index of [targetOrdinal] when the anchor at [performanceOrdinal]
 * is set 1. With [skipMinisInFatigueIndex] (the STR-232 match-cluster anchor),
 * auto-generated minis between the anchor and the target consume no steps — the
 * backoff and its completed cluster count as the one normal set they replace —
 * while every other set (working sets, drops) still counts as before.
 */
fun fatigueSetIndex(
    setsByPosition: List<RenderedSet>,
    performanceOrdinal: Int,
    targetOrdinal: Int,
    skipMinisInFatigueIndex: Boolean,
): Int {
    if (!skipMinisInFatigueIndex || performanceOrdinal !in setsByPosition.indices) {
        return fatigueSetIndex(performanceOrdinal, targetOrdinal)
    }
    val to = targetOrdinal.coerceAtMost(setsByPosition.lastIndex)
    if (to <= performanceOrdinal) return 1
    val workingSteps =
        (performanceOrdinal + 1..to).count { index -> !setsByPosition[index].isAutoGeneratedMyoMini() }
    return (workingSteps + 1).coerceAtLeast(1)
}

fun remainingCountAfterPerformanceAnchor(
    setsByPosition: List<RenderedSet>,
    performanceOrdinal: Int,
    lastUpcomingOrdinal: Int,
    skipMinisInFatigueIndex: Boolean = false,
): Int =
    (
        fatigueSetIndex(
            setsByPosition,
            performanceOrdinal,
            lastUpcomingOrdinal,
            skipMinisInFatigueIndex,
        ) - 1
        ).coerceAtLeast(0)

/**
 * True when [this] set is a straight working set: standard sets, plus myo
 * activations (template / top). Live minis are overlay-only and never straight
 * working; drop sets are their own pipeline.
 */
fun RenderedSet.isStraightWorkingSet(): Boolean =
    when (setType) {
        SetType.Standard -> true
        SetType.MyoRep -> !isAutoGeneratedMyoMini()
        SetType.DropSet -> false
    }

/**
 * Capacity + set-index origin for projecting remaining straight-set reps.
 * [indexOriginOrdinal] is the "set 1" of the fatigue story in [setsByPosition] order.
 */
data class FatigueGeometry(
    val capacityLogged: LoggedSetValue,
    val indexOriginOrdinal: Int,
    /** STR-232 match-cluster geometry: minis consume no fatigue steps. */
    val skipMinisInFatigueIndex: Boolean = false,
)

fun matchesShownPrescription(
    set: RenderedSet,
    logged: LoggedSetValue,
    priorRecommendations: Map<SetSlotId, LiveSetRecommendation>,
): Boolean {
    val prior = priorRecommendations[set.slotId]
    // Top set never has a live prior row — fall back to snapshot recommendedReps so
    // "exact prescription" still requires matching the shown rep target, not only RIR.
    val shownReps =
        prior?.reps?.takeIf { it > 0 }
            ?: set.recommendedReps.takeIf { it > 0 }
    if (shownReps != null && logged.reps != shownReps) return false
    // Null RIR is never "as prescribed" — adaptive path re-evaluates.
    if (logged.rir != set.rirGoal) return false
    return true
}

fun stableBlockGeometry(setsByPosition: List<RenderedSet>): FatigueGeometry? {
    val firstStraight =
        setsByPosition.firstOrNull { it.isStraightWorkingSet() } ?: return null
    val firstOrdinal =
        setsByPosition.indexOfFirst { it.slotId == firstStraight.slotId }
            .takeIf { it >= 0 } ?: return null
    val capacityLogged =
        firstStraight.loggedValue
            ?: setsByPosition
                .firstOrNull { it.isStraightWorkingSet() && it.loggedValue != null }
                ?.loggedValue
            ?: run {
                val weight =
                    firstStraight.recommendedWeight.takeIf { it.amount > 0.0 }
                        ?: return null
                val reps =
                    firstStraight.recommendedReps.takeIf { it > 0 } ?: return null
                LoggedSetValue(
                    slotId = firstStraight.slotId,
                    weight = weight,
                    reps = reps,
                    rir = firstStraight.rirGoal.coerceAtLeast(0),
                )
            }
    return FatigueGeometry(
        capacityLogged = capacityLogged,
        indexOriginOrdinal = firstOrdinal,
    )
}

data class StraightBlock(
    val performanceAnchor: RenderedSet,
    val performanceLogged: LoggedSetValue,
    val performanceOrdinal: Int,
    val lastUpcoming: RenderedSet,
    val remainingCount: Int,
    /** True when a mini/drop sits after the e1RM anchor (open or completed). */
    val forceLiveWeight: Boolean,
    /** True for the STR-232 match-cluster anchor: minis consume no fatigue steps. */
    val skipMinisInFatigueIndex: Boolean = false,
)

/**
 * Shared straight-block geometry for weight + rep projection.
 * [remainingCount] and [fatigueSetIndex] both use ordinals so open minis/drops
 * between activation and the last standard count the same way — except under the
 * STR-232 match-cluster anchor, where completed minis consume no steps.
 */
fun resolveStraightBlock(
    setsByPosition: List<RenderedSet>,
    lastPerformedSet: RenderedSet,
    lastPerformed: LoggedSetValue,
    anchorOrdinal: Int,
    straightUpcoming: List<RenderedSet>,
): StraightBlock? {
    if (straightUpcoming.isEmpty()) return null
    // STR-232: a just-completed rep-match mini cluster re-roots the block at the
    // match activation (see resolveMatchClusterActivation); every other case keeps
    // the latest straight-working anchor.
    val matchActivation = resolveMatchClusterActivation(setsByPosition, lastPerformedSet)
    val performanceAnchor =
        matchActivation
            ?: resolveStraightPerformanceAnchor(setsByPosition, lastPerformedSet)
    val performanceLogged = performanceAnchor.loggedValue ?: lastPerformed
    val performanceOrdinal =
        setsByPosition
            .indexOfFirst { it.slotId == performanceAnchor.slotId }
            .let { if (it < 0) anchorOrdinal else it }
    val lastUpcoming = straightUpcoming.last()
    val lastUpcomingOrdinal =
        setsByPosition
            .indexOfFirst { it.slotId == lastUpcoming.slotId }
            .let { if (it < 0) performanceOrdinal + straightUpcoming.size else it }
    val skipMinis = matchActivation != null
    val remainingCount =
        remainingCountAfterPerformanceAnchor(
            setsByPosition = setsByPosition,
            performanceOrdinal = performanceOrdinal,
            lastUpcomingOrdinal = lastUpcomingOrdinal,
            skipMinisInFatigueIndex = skipMinis,
        )
    val forceLiveWeight =
        mustForceLiveStraightWeight(
            performanceAnchor = performanceAnchor,
            lastPerformedSet = lastPerformedSet,
            setsByPosition = setsByPosition,
            performanceOrdinal = performanceOrdinal,
        )
    return StraightBlock(
        performanceAnchor = performanceAnchor,
        performanceLogged = performanceLogged,
        performanceOrdinal = performanceOrdinal,
        lastUpcoming = lastUpcoming,
        remainingCount = remainingCount,
        forceLiveWeight = forceLiveWeight,
        skipMinisInFatigueIndex = skipMinis,
    )
}

private fun mustForceLiveStraightWeight(
    performanceAnchor: RenderedSet,
    lastPerformedSet: RenderedSet,
    setsByPosition: List<RenderedSet>,
    performanceOrdinal: Int,
): Boolean {
    if (performanceAnchor.slotId != lastPerformedSet.slotId) return true
    return setsByPosition.withIndex().any { (index, set) ->
        index > performanceOrdinal && set.isIntensifierSlot()
    }
}

private fun resolveStraightPerformanceAnchor(
    setsByPosition: List<RenderedSet>,
    lastPerformedSet: RenderedSet,
): RenderedSet {
    val lastIdx = setsByPosition.indexOfFirst { it.slotId == lastPerformedSet.slotId }
    if (lastIdx < 0) return lastPerformedSet
    return setsByPosition
        .take(lastIdx + 1)
        .lastOrNull { it.loggedValue != null && it.isStraightWorkingSet() }
        ?: lastPerformedSet
}

private fun RenderedSet.isIntensifierSlot(): Boolean =
    isAutoGeneratedMyoMini() || setType == SetType.DropSet
