package com.stratum.domain.workout

import com.stratum.domain.program.LiftSet
import com.stratum.domain.program.SetType
import com.stratum.domain.program.Workout
import com.stratum.domain.program.WorkoutLift
import com.stratum.domain.program.identity.LiftSetId
import com.stratum.domain.program.identity.WorkoutLiftId
import java.util.UUID
import javax.inject.Inject

/**
 * Maps session-only [WorkoutOverlay] structural edits back onto a baseline [Workout] template
 * so the changes can be persisted via `SaveWorkoutUseCase`. Only the structural fields are
 * applied — logged sets and live recommendations are session activity, not template edits.
 *
 * Applied overlay fields: swapped lifts, swapped equipment, deleted lifts, added lifts,
 * deleted sets, added sets, superset group overrides, rest-timer-between-lifts overrides,
 * per-slot rest-seconds overrides, per-slot set-type/shape overrides, and lift reordering.
 *
 * Overlay-added slots that are also present in [WorkoutOverlay.deletedSlotIds] are **not**
 * written to the template (matches live merge semantics). Live-generated myo mini-sets
 * (overlay MyoRep slots that are not activations) are also excluded — they are session-only.
 */
class ApplyOverlayToWorkoutUseCase @Inject constructor() {
    operator fun invoke(baseline: Workout, overlay: WorkoutOverlay): Workout {
        val liveAddedSlots =
            overlay.addedSlots
                .filterNot { it.slotId in overlay.deletedSlotIds }
                .map { it.applyShapeOverride(overlay) }
                // Auto-generated myo minis are live-only; never author them onto the template.
                .filterNot { it.isAutoGeneratedMyoMini() }

        val updatedLifts = baseline.workoutLifts
            .filterNot { it.id in overlay.deletedLiftIds }
            .map { lift ->
                val swappedLiftId = overlay.swappedLifts[lift.id]
                val updatedLiftId = swappedLiftId ?: lift.liftId

                val supersetOverride = overlay.supersetGroupIdOverrides[lift.id]
                val updatedSupersetGroupId = if (overlay.supersetGroupIdOverrides.containsKey(lift.id)) {
                    supersetOverride
                } else {
                    lift.supersetGroupId
                }

                val updatedRestTimer = overlay.useRestTimerBetweenLiftsOverrides[lift.id]
                    ?: lift.useRestTimerBetweenLifts

                val deletedTemplateSetIds = overlay.deletedSlotIds
                    .filterIsInstance<SetSlotId.Template>()
                    .map { it.liftSetId }
                    .toSet()

                val remainingSets = lift.sets
                    .filterNot { it.id in deletedTemplateSetIds }
                    .map { set -> set.applyOverlayFields(overlay) }

                val addedSets = liveAddedSlots
                    .filter { it.workoutLiftId == lift.id }
                    .map { slot -> slot.toLiftSet(lift.id, overlay) }

                val allSets = (remainingSets + addedSets)
                    .sortedBy { it.position }
                    .mapIndexed { index, set -> set.copy(position = index) }

                // STR-127: a lift swap re-scopes row-held state to the new pair.
                // Equipment resets to the new lift's default (null = inherit it)
                // unless an explicit session equipment swap targets the new pair;
                // pinned notes resolve pair-aware so the old lift's notes are
                // never written onto the incoming lift (its own pair's notes —
                // stashed or none — are written instead).
                val pairNotes =
                    if (swappedLiftId != null) {
                        resolvedWorkoutPinnedNotes(
                            overlay,
                            lift.id,
                            templateLiftId = lift.liftId,
                            templateNotes = lift.effectiveNotes(),
                        )
                    } else {
                        null
                    }
                lift.copy(
                    liftId = updatedLiftId,
                    sets = allSets,
                    supersetGroupId = updatedSupersetGroupId,
                    useRestTimerBetweenLifts = updatedRestTimer,
                    // Save-back persists the resolved pair equipment: the session
                    // override, else the template assignment when it belongs to
                    // this pair (null after a pair swap = inherit the new lift's
                    // default at render).
                    equipmentId =
                        resolveSessionEquipmentId(
                            swapOverrideId = overlay.swappedEquipment[lift.id],
                            templateEquipmentId =
                                templateEquipmentIdForPair(
                                    swappedLiftId = swappedLiftId,
                                    templateLiftId = lift.liftId,
                                    hasSessionEquipmentOverride =
                                        overlay.swappedEquipment.containsKey(lift.id),
                                    templateEquipmentId = lift.equipmentId,
                                ),
                            liftEquipmentId = null,
                        ),
                    pinnedNote =
                        if (swappedLiftId != null) {
                            pairNotes?.firstOrNull()
                        } else {
                            resolvedWorkoutPinnedNoteFirst(
                                overlay,
                                lift.id,
                                lift.pinnedNote,
                            )
                        },
                    pinnedNotes =
                        pairNotes
                            ?: resolvedWorkoutPinnedNotes(
                                overlay.workoutLiftPinnedNoteLists,
                                lift.id,
                                lift.pinnedNotes,
                            ),
                )
            }

        val existingIds = updatedLifts.map { it.id }.toSet()
        val newlyAddedLifts = overlay.addedLifts
            .filterNot { it.workoutLiftId in overlay.deletedLiftIds }
            .filterNot { it.workoutLiftId in existingIds }
            .map { added ->
                val slots = liveAddedSlots
                    .filter { it.workoutLiftId == added.workoutLiftId }
                    .sortedBy { it.position }
                val sets = if (slots.isEmpty()) {
                    listOf(
                        LiftSet(
                            id = LiftSetId(UUID.randomUUID().toString()),
                            workoutLiftId = added.workoutLiftId,
                            position = 0,
                            setType = SetType.Standard,
                            repMin = AddedLiftDefaults.REP_MIN,
                            repMax = AddedLiftDefaults.REP_MAX,
                            rirGoal = AddedLiftDefaults.RIR,
                            isTopSet = true,
                            restSeconds = AddedLiftDefaults.REST_SECONDS,
                        ),
                    )
                } else {
                    slots.mapIndexed { index, slot ->
                        slot.toLiftSet(added.workoutLiftId, overlay).copy(position = index)
                    }
                }
                val restOverride = overlay.useRestTimerBetweenLiftsOverrides[added.workoutLiftId]
                val groupOverride = if (overlay.supersetGroupIdOverrides.containsKey(added.workoutLiftId)) {
                    overlay.supersetGroupIdOverrides[added.workoutLiftId]
                } else {
                    added.supersetGroupId
                }
                // STR-127 pair scoping for a swapped session-added lift: the
                // effective lift is the swapped-in one, equipment falls back to
                // its default (the swappedEquipment lookup below already yields
                // null after a lift swap cleared the old pair's override), and
                // notes resolve pair-aware against the added lift as template.
                val effectiveAddedLiftId =
                    overlay.swappedLifts[added.workoutLiftId] ?: added.liftId
                val addedPairNotes =
                    resolvedWorkoutPinnedNotes(
                        overlay,
                        added.workoutLiftId,
                        templateLiftId = added.liftId,
                        templateNotes = emptyList(),
                    )
                WorkoutLift(
                    id = added.workoutLiftId,
                    workoutId = baseline.id,
                    liftId = effectiveAddedLiftId,
                    progressionScheme = added.progressionScheme,
                    // Temporary; renumbered after final order is known.
                    position = 0,
                    sets = sets,
                    supersetGroupId = groupOverride,
                    useRestTimerBetweenLifts = restOverride ?: added.useRestTimerBetweenLifts,
                    equipmentId = overlay.swappedEquipment[added.workoutLiftId],
                    pinnedNote =
                        if (overlay.swappedLifts.containsKey(added.workoutLiftId)) {
                            addedPairNotes.firstOrNull()
                        } else {
                            resolvedWorkoutPinnedNoteFirst(
                                overlay,
                                added.workoutLiftId,
                                templateNote = null,
                            )
                        },
                    pinnedNotes =
                        if (overlay.swappedLifts.containsKey(added.workoutLiftId)) {
                            addedPairNotes
                        } else {
                            resolvedWorkoutPinnedNotes(
                                overlay.workoutLiftPinnedNoteLists,
                                added.workoutLiftId,
                                templateNotes = emptyList(),
                            )
                        },
                )
            }

        val combined = updatedLifts + newlyAddedLifts

        val reorderedLifts = overlay.orderedLiftIds?.let { orderedIds ->
            val orderIndex = orderedIds.withIndex().associate { (index, id) -> id to index }
            combined.sortedBy { lift ->
                orderIndex[lift.id.value] ?: Int.MAX_VALUE
            }
        } ?: combined

        // Room loads workout_lifts ORDER BY position — keep field in sync with list order.
        val positioned =
            reorderedLifts.mapIndexed { index, lift ->
                lift.copy(position = index)
            }

        return baseline.copy(workoutLifts = positioned)
    }

    private fun SetSlot.toLiftSet(workoutLiftId: WorkoutLiftId, overlay: WorkoutOverlay): LiftSet {
        val shaped = applyShapeOverride(overlay)
        return LiftSet(
            id = LiftSetId(UUID.randomUUID().toString()),
            workoutLiftId = workoutLiftId,
            position = shaped.position,
            setType = shaped.setType,
            repMin = shaped.repMin,
            repMax = shaped.repMax,
            rirGoal = shaped.rirGoal,
            isTopSet = shaped.isTopSet,
            restSeconds = overlay.restSecondsOverrides[slotId] ?: shaped.restSeconds,
            myoRepKind = shaped.myoRepKind,
        )
    }

    private fun LiftSet.applyOverlayFields(overlay: WorkoutOverlay): LiftSet {
        val slotId = SetSlotId.Template(id)
        val shape = overlay.slotShapeOverrides[slotId]
        val restOverride = overlay.restSecondsOverrides[slotId]
        if (shape == null && restOverride == null) return this
        return if (shape != null) {
            copy(
                setType = shape.setType,
                myoRepKind = shape.myoRepKind,
                isTopSet = shape.isTopSet,
                repMin = shape.repMin,
                repMax = shape.repMax,
                rirGoal = shape.rirGoal,
                restSeconds = restOverride ?: restSeconds,
            )
        } else {
            copy(restSeconds = restOverride ?: restSeconds)
        }
    }

}
