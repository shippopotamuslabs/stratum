/**
 * Live-session intensifier helpers (myo mini generation + cascade deletes).
 * Split from [LiveWorkoutOverlayOps] to stay under Detekt TooManyFunctions.
 */
internal object LiveIntensifierOverlayOps {

    fun applyMyoLifecycleAfterLog(
        structure: WorkoutStructureProjection?,
        overlay: WorkoutOverlay,
        loggedSlotId: SetSlotId,
        lifecycle: MyoRepLifecycle = DefaultMyoRepLifecycle(),
    ): WorkoutOverlay {
        val workoutLiftId = LiveWorkoutOverlayOps.resolveSlot(structure, overlay, loggedSlotId)
            ?.workoutLiftId
            ?: return overlay
        val slots = LiveWorkoutOverlayOps.visibleSlotsForLift(structure, overlay, workoutLiftId)
            .sortedBy { it.position }
        val context = myoLogContext(slots, overlay, loggedSlotId) ?: return overlay
        if (!shouldGenerateMyoMini(context)) return overlay

        val next = lifecycle.nextMiniSet(context.blockState) ?: return overlay
        val insertPosition = context.insertPosition
        val parentKey = slotIdKey(context.clusterAnchor.slotId)
        val miniRest =
            when (context.kind) {
                MyoRepKind.RepMatching ->
                    RestDefaultForTransition.MYO_MINI_DEFAULT_REST_SECONDS
                MyoRepKind.RepFloor ->
                    context.blockState.restSeconds.coerceAtLeast(0)
            }
        val unique = next.copy(
            slotId = SetSlotId.Overlay(
                OverlaySetInstanceId(
                    "mini-$parentKey-" +
                        "${context.minis.size + 1}-${UUID.randomUUID().toString().take(8)}",
                ),
            ),
            position = insertPosition,
            restSeconds = miniRest,
            myoRepKind = context.kind,
        )
        // Seed baseline from cluster anchor (backoff) weight when present, else activation.
        val anchorLog = overlay.loggedSets[context.clusterAnchor.slotId]
        val activationLog = overlay.loggedSets[context.activation.slotId]
        val seedWeight =
            anchorLog?.weight
                ?: activationLog?.weight
                ?: Weight(0.0, Weight.WeightUnit.Lb)
        val seedBaseline = SlotRecommendation(
            slotId = unique.slotId,
            recommendedWeight = seedWeight,
            baselineExpectedReps = 0,
        )
        val withMini =
            overlay.apply(
                StructuralMutation.GenerateMyoRepMiniSet(
                    activationSlotId = context.activation.slotId,
                    newSlot = unique,
                ),
            )
        return withMini.copy(
            dynamicBaselines = withMini.dynamicBaselines + (unique.slotId to seedBaseline),
        )
    }

    fun cascadeDeleteTargets(
        structure: WorkoutStructureProjection?,
        overlay: WorkoutOverlay,
        slotId: SetSlotId,
    ): List<SetSlotId> {
        val slot = LiveWorkoutOverlayOps.resolveSlot(structure, overlay, slotId)
            ?: return listOf(slotId)
        val slots = LiveWorkoutOverlayOps.visibleSlotsForLift(structure, overlay, slot.workoutLiftId)
        val idx = slots.indexOfFirst { it.slotId == slotId }
        if (idx < 0) return listOf(slotId)

        return when (slot.setType) {
            SetType.MyoRep -> myoCascadeDeleteTargets(slots, slot, slotId)
            else -> dropCascadeDeleteTargets(slots, idx, slot, slotId)
        }
    }

    /**
     * Slot ids whose **logs** (and auto-minis) clear when [slotId] is unlogged.
     *
     * - Match activation → activation log + every mini under each match backoff
     *   (backoff **rows** stay; their logs stay — only cluster minis regenerate).
     * - Match backoff / floor activation → self log + contiguous minis (minis deleted).
     * - Mini → self only.
     */
    fun unlogCascadeTargets(
        structure: WorkoutStructureProjection?,
        overlay: WorkoutOverlay,
        slotId: SetSlotId,
    ): UnlogCascade {
        val selfOnly = UnlogCascade(logTargets = listOf(slotId), minisToDelete = emptyList())
        val slot = LiveWorkoutOverlayOps.resolveSlot(structure, overlay, slotId) ?: return selfOnly
        val slots = LiveWorkoutOverlayOps.visibleSlotsForLift(structure, overlay, slot.workoutLiftId)
        val index = slots.indexOfFirst { it.slotId == slotId }
        if (index < 0 || slot.setType != SetType.MyoRep || slot.isAutoGeneratedMyoMini()) {
            return selfOnly
        }
        val minis =
            if (MyoMatchStructure.isMyoMatchActivation(slots, index)) {
                val collected = mutableListOf<SetSlotId>()
                collected += MyoMatchStructure.contiguousMinisAfter(slots, slot).map { it.slotId }
                for (backoff in MyoMatchStructure.matchBackoffsAfter(slots, index)) {
                    collected += MyoMatchStructure.contiguousMinisAfter(slots, backoff).map { it.slotId }
                }
                collected.distinct()
            } else {
                // Floor activation or match backoff: contiguous minis only.
                MyoMatchStructure.contiguousMinisAfter(slots, slot).map { it.slotId }
            }
        return UnlogCascade(
            logTargets = listOf(slotId) + minis,
            minisToDelete = minis,
        )
    }

    data class UnlogCascade(
        val logTargets: List<SetSlotId>,
        val minisToDelete: List<SetSlotId>,
    )

    /**
     * Match activation deletes its match backoffs + all minis in the block.
     * Match backoff deletes itself + its minis only.
     * Floor activation deletes its minis only.
     * A mini deletes only itself.
     */
    private fun myoCascadeDeleteTargets(
        slots: List<SetSlot>,
        slot: SetSlot,
        slotId: SetSlotId,
    ): List<SetSlotId> {
        if (slot.isAutoGeneratedMyoMini()) return listOf(slotId)

        val index = slots.indexOfFirst { it.slotId == slotId }
        if (index < 0) return listOf(slotId)

        if (MyoMatchStructure.isMyoMatchActivation(slots, index)) {
            val targets = mutableListOf(slotId)
            targets += MyoMatchStructure.matchBackoffsAfter(slots, index).map { it.slotId }
            // Minis under activation (floor-style, none for match) + under each backoff.
            targets += MyoMatchStructure.contiguousMinisAfter(slots, slot).map { it.slotId }
            for (backoff in MyoMatchStructure.matchBackoffsAfter(slots, index)) {
                targets += MyoMatchStructure.contiguousMinisAfter(slots, backoff).map { it.slotId }
            }
            return targets.distinct()
        }

        if (MyoMatchStructure.isMyoMatchBackoff(slots, index) ||
            (slot.setType == SetType.MyoRep && !slot.isAutoGeneratedMyoMini())
        ) {
            // Floor activation or match backoff: self + contiguous minis after.
            val targets = mutableListOf(slotId)
            targets += MyoMatchStructure.contiguousMinisAfter(slots, slot).map { it.slotId }
            return targets
        }

        return listOf(slotId)
    }

    private fun dropCascadeDeleteTargets(
        slots: List<SetSlot>,
        idx: Int,
        slot: SetSlot,
        slotId: SetSlotId,
    ): List<SetSlotId> {
        val targets = mutableListOf(slotId)
        var i = idx + 1
        while (i < slots.size && slots[i].setType == SetType.DropSet) {
            targets += slots[i].slotId
            i++
        }
        return if (slot.setType == SetType.DropSet || targets.size > 1) targets else listOf(slotId)
    }

    fun requiresCascadeConfirm(
        structure: WorkoutStructureProjection?,
        overlay: WorkoutOverlay,
        slotId: SetSlotId,
    ): Boolean = cascadeDeleteTargets(structure, overlay, slotId).size > 1

    private data class MyoLogContext(
        val activation: SetSlot,
        val clusterAnchor: SetSlot,
        val minis: List<SetSlot>,
        val kind: MyoRepKind,
        val blockState: MyoRepBlockState,
        val loggedSlotId: SetSlotId,
        val loggedSlotIds: Set<SetSlotId>,
        val insertPosition: Int,
    )

    private fun myoLogContext(
        slots: List<SetSlot>,
        overlay: WorkoutOverlay,
        loggedSlotId: SetSlotId,
    ): MyoLogContext? {
        val loggedSlot = slots.firstOrNull { it.slotId == loggedSlotId } ?: return null
        if (loggedSlot.setType != SetType.MyoRep) return null

        val kind = loggedSlot.myoRepKind
            ?: findMyoActivation(slots, loggedSlot)?.myoRepKind
            ?: MyoRepKind.RepFloor

        return when (kind) {
            MyoRepKind.RepFloor -> floorLogContext(slots, overlay, loggedSlot)
            MyoRepKind.RepMatching -> matchLogContext(slots, overlay, loggedSlot)
        }
    }

    private fun floorLogContext(
        slots: List<SetSlot>,
        overlay: WorkoutOverlay,
        loggedSlot: SetSlot,
    ): MyoLogContext? {
        val activation = findMyoActivation(slots, loggedSlot) ?: return null
        val minis = MyoMatchStructure.contiguousMinisAfter(slots, activation)
        val activationLogged = overlay.loggedSets[activation.slotId] ?: return null
        val miniLogs = minis.mapNotNull { mini -> overlay.loggedSets[mini.slotId] }
        val state = MyoRepBlockState(
            workoutLiftId = activation.workoutLiftId,
            activationSlotId = activation.slotId,
            kind = MyoRepKind.RepFloor,
            activationReps = activationLogged.reps,
            repFloor = MyoRepLifecycle.DEFAULT_REP_FLOOR,
            cumulativeMiniSetReps = miniLogs.sumOf { it.reps },
            lastMiniSetReps = miniLogs.lastOrNull()?.reps,
            generatedSlots = minis,
            liftId = activation.liftId,
            activationPosition = activation.position,
            restSeconds = activation.restSeconds.coerceAtLeast(0),
        )
        val activationIndex = slots.indexOfFirst { it.slotId == activation.slotId }
        val insertPosition =
            if (activationIndex >= 0) {
                activationIndex + 1 + minis.size
            } else {
                activation.position + 1 + minis.size
            }
        return MyoLogContext(
            activation = activation,
            clusterAnchor = activation,
            minis = minis,
            kind = MyoRepKind.RepFloor,
            blockState = state,
            loggedSlotId = loggedSlot.slotId,
            loggedSlotIds = overlay.loggedSets.keys,
            insertPosition = insertPosition,
        )
    }

    private fun matchLogContext(
        slots: List<SetSlot>,
        overlay: WorkoutOverlay,
        loggedSlot: SetSlot,
    ): MyoLogContext? {
        val activation = MyoMatchStructure.resolveMatchActivation(slots, loggedSlot) ?: return null
        // Match activation never owns a mini cluster.
        val isActivationLog =
            MyoMatchStructure.isMyoMatchActivation(slots, activation) &&
                loggedSlot.slotId == activation.slotId
        val clusterAnchor = MyoMatchStructure.resolveClusterAnchor(slots, loggedSlot)
        val anchor =
            clusterAnchor?.takeUnless { MyoMatchStructure.isMyoMatchActivation(slots, it) }
        if (isActivationLog || anchor == null) return null
        val activationLogged = overlay.loggedSets[activation.slotId] ?: return null
        val minis = MyoMatchStructure.contiguousMinisAfter(slots, anchor)
        val anchorLog = overlay.loggedSets[anchor.slotId]
        val miniLogs = minis.mapNotNull { mini -> overlay.loggedSets[mini.slotId] }
        val clusterTotal = (anchorLog?.reps ?: 0) + miniLogs.sumOf { it.reps }

        val state = MyoRepBlockState(
            workoutLiftId = activation.workoutLiftId,
            activationSlotId = activation.slotId,
            kind = MyoRepKind.RepMatching,
            activationReps = activationLogged.reps,
            repFloor = 0,
            cumulativeMiniSetReps = miniLogs.sumOf { it.reps },
            lastMiniSetReps = miniLogs.lastOrNull()?.reps,
            generatedSlots = minis,
            liftId = activation.liftId,
            activationPosition = activation.position,
            restSeconds = RestDefaultForTransition.MYO_MINI_DEFAULT_REST_SECONDS,
            clusterAnchorSlotId = anchor.slotId,
            clusterAnchorPosition = anchor.position,
            cumulativeClusterReps = clusterTotal,
        )
        val anchorIndex = slots.indexOfFirst { it.slotId == anchor.slotId }
        val insertPosition =
            if (anchorIndex >= 0) {
                anchorIndex + 1 + minis.size
            } else {
                anchor.position + 1 + minis.size
            }
        return MyoLogContext(
            activation = activation,
            clusterAnchor = anchor,
            minis = minis,
            kind = MyoRepKind.RepMatching,
            blockState = state,
            loggedSlotId = loggedSlot.slotId,
            loggedSlotIds = overlay.loggedSets.keys,
            insertPosition = insertPosition,
        )
    }

    /**
     * Spawn another mini only when the cluster has no open (unlogged) mini already, and the
     * log that triggered this was either the cluster anchor (floor activation / match backoff)
     * or the last mini in the cluster.
     */
    private fun shouldGenerateMyoMini(context: MyoLogContext): Boolean {
        val lastMini = context.minis.maxByOrNull { it.position }
        val openClusterMini = lastMini != null && lastMini.slotId !in context.loggedSlotIds
        if (openClusterMini) return false
        return if (context.loggedSlotId == context.clusterAnchor.slotId) {
            true
        } else {
            lastMini != null && lastMini.slotId == context.loggedSlotId
        }
    }

    /** Authored myo row (template or re-typed) — not a live-generated mini. */
    private fun isMyoActivation(slot: SetSlot): Boolean =
        slot.setType == SetType.MyoRep && !slot.isAutoGeneratedMyoMini()

    /**
     * Resolves the floor activation for a myo mini, or the slot itself when it is an activation.
     * Multiple clusters per lift: an activation never walks back to a prior cluster.
     */
    private fun findMyoActivation(slots: List<SetSlot>, from: SetSlot): SetSlot? {
        if (from.setType != SetType.MyoRep) return null
        return when {
            MyoMatchStructure.isMyoMatchKind(from) ->
                MyoMatchStructure.resolveMatchActivation(slots, from)
            isMyoActivation(from) -> from
            from.isAutoGeneratedMyoMini() ->
                slots
                    .filter { it.position <= from.position }
                    .lastOrNull {
                        isMyoActivation(it) && !MyoMatchStructure.isMyoMatchBackoff(slots, it)
                    }
                    ?: slots
                        .filter { it.position <= from.position }
                        .lastOrNull { isMyoActivation(it) }
            else -> null
        }
    }

    private fun slotIdKey(id: SetSlotId): String = when (id) {
        is SetSlotId.Template -> id.liftSetId.value
        is SetSlotId.Overlay -> id.instanceId.value
    }

    /**
     * Orders template + overlay slots.
     * - Auto-generated myo minis insert at **parentIndex + 1** (after that parent's minis).
     * - Live match backoffs (`match-bo-{parentKey}-…`) insert immediately after their parent
     *   (activation or prior backoff), so they stay contiguous even when trailing Standards
     *   already occupy later template positions.
     * - Other overlay sets insert by [SetSlot.position].
     * Result positions renumbered 0..n-1.
     */
    fun orderLiftSlots(
        templateSlots: List<SetSlot>,
        addedSlots: List<SetSlot>,
    ): List<SetSlot> {
        val result = templateSlots.sortedBy { it.position }.toMutableList()
        for (added in addedSlots) {
            insertAddedSlot(result, added)
        }
        return result.mapIndexed { index, slot -> slot.copy(position = index) }
    }

    private fun insertAddedSlot(result: MutableList<SetSlot>, added: SetSlot) {
        val parentPrefix =
            when {
                added.isAutoGeneratedMyoMini() -> "mini-"
                isMatchBackoffOverlay(added) -> "match-bo-"
                else -> null
            }
        if (parentPrefix == null) {
            insertByPosition(result, added)
            return
        }
        val parentIndex = indexOfEmbeddedParent(result, added, prefix = parentPrefix)
        if (parentIndex < 0) {
            insertByPosition(result, added)
            return
        }
        // After parent, after any minis already hanging under that parent.
        var insertAt = parentIndex + 1
        while (
            insertAt < result.size &&
            result[insertAt].isAutoGeneratedMyoMini() &&
            indexOfEmbeddedParent(result, result[insertAt], prefix = "mini-") == parentIndex
        ) {
            insertAt++
        }
        result.add(insertAt, added)
    }

    private fun insertByPosition(result: MutableList<SetSlot>, added: SetSlot) {
        var insertAt = result.indexOfLast { it.position < added.position } + 1
        if (insertAt < 0) insertAt = 0
        while (insertAt < result.size && result[insertAt].position == added.position) {
            insertAt++
        }
        result.add(insertAt.coerceIn(0, result.size), added)
    }

    private fun isMatchBackoffOverlay(slot: SetSlot): Boolean {
        val id = (slot.slotId as? SetSlotId.Overlay)?.instanceId?.value ?: return false
        return id.startsWith("match-bo-")
    }

    /**
     * Parent of an overlay whose instance id is `{prefix}{parentKey}-…` is the non-mini
     * slot whose [slotIdKey] is the longest matching prefix. Matched by **slot id only**
     * so session-retyped anchors still win.
     */
    private fun indexOfEmbeddedParent(
        slots: List<SetSlot>,
        child: SetSlot,
        prefix: String,
    ): Int {
        val id = (child.slotId as? SetSlotId.Overlay)?.instanceId?.value ?: return -1
        if (!id.startsWith(prefix)) return -1
        val rest = id.removePrefix(prefix)
        return slots.withIndex()
            .filter { (_, slot) -> !slot.isAutoGeneratedMyoMini() }
            .mapNotNull { (index, slot) ->
                val key = slotIdKey(slot.slotId)
                if (key.isNotEmpty() && rest.startsWith("$key-")) {
                    index to key.length
                } else {
                    null
                }
            }
            .maxByOrNull { (_, keyLength) -> keyLength }
            ?.first
            ?: -1
    }
}
