/** Presentation / ViewModel set kinds for live type changes (S / M / MM / D). */
enum class LiveSetKind {
    Standard,
    MyoRepFloor,
    MyoRepMatch,
    DropSet,
}

/**
 * Live-session set-type changes (template Edit Workout parity).
 *
 * Auto-generated myo minis cannot change type. Demoting a myo activation discards its
 * contiguous minis (and match backoffs for MM) while keeping the activation's logged values.
 */
internal object LiveSetTypeOverlayOps {

    fun LiveSetKind.toDomainSetType(): SetType =
        when (this) {
            LiveSetKind.Standard -> SetType.Standard
            LiveSetKind.MyoRepFloor, LiveSetKind.MyoRepMatch -> SetType.MyoRep
            LiveSetKind.DropSet -> SetType.DropSet
        }

    fun LiveSetKind.toMyoRepKind(): MyoRepKind? =
        when (this) {
            LiveSetKind.MyoRepFloor -> MyoRepKind.RepFloor
            LiveSetKind.MyoRepMatch -> MyoRepKind.RepMatching
            LiveSetKind.Standard, LiveSetKind.DropSet -> null
        }

    fun domainToLiveSetKind(setType: SetType, myoRepKind: MyoRepKind?): LiveSetKind =
        when (setType) {
            SetType.Standard -> LiveSetKind.Standard
            SetType.DropSet -> LiveSetKind.DropSet
            SetType.MyoRep ->
                when (myoRepKind) {
                    MyoRepKind.RepMatching -> LiveSetKind.MyoRepMatch
                    MyoRepKind.RepFloor, null -> LiveSetKind.MyoRepFloor
                }
        }

    private fun LiveSetKind.isMyo(): Boolean =
        this == LiveSetKind.MyoRepFloor || this == LiveSetKind.MyoRepMatch

    /**
     * Whether [kind] can be selected for [setIndex] on the given lift slots.
     * Mirrors template [IntensifierPlacementRules] + Edit Workout chip enablement.
     * Match backoffs are type-locked (managed with the activation).
     */
    fun canSelectSetKind(
        slots: List<SetSlot>,
        setIndex: Int,
        kind: LiveSetKind,
        scheme: ProgressionScheme,
        loadType: LoadType,
    ): Boolean {
        if (setIndex !in slots.indices) return false
        val slot = slots[setIndex]
        // Auto-generated minis are type-locked (only the activation is editable).
        if (slot.isAutoGeneratedMyoMini()) return false
        // Match backoffs are not re-typed via the chip.
        if (MyoMatchStructure.isMyoMatchBackoff(slots, setIndex)) return false
        if (kind == LiveSetKind.Standard) return true

        return when (kind) {
            LiveSetKind.DropSet -> {
                val previousType = slots.getOrNull(setIndex - 1)?.setType
                IntensifierPlacementRules.isDropAllowed(
                    position = setIndex,
                    previousType = previousType,
                    scheme = scheme,
                    loadType = loadType,
                )
            }
            LiveSetKind.MyoRepFloor, LiveSetKind.MyoRepMatch ->
                IntensifierPlacementRules.isMyoAllowed(
                    position = setIndex,
                    setCount = slots.size,
                    scheme = scheme,
                )
            LiveSetKind.Standard -> true
        }
    }

    /**
     * Contiguous auto-generated minis that would be removed if [slotId] leaves MyoRep.
     * Empty when the slot is not a myo activation or has no minis.
     */
    fun miniSlotsDiscardedOnDemote(
        structure: WorkoutStructureProjection?,
        overlay: WorkoutOverlay,
        slotId: SetSlotId,
    ): List<SetSlotId> {
        val slot = LiveWorkoutOverlayOps.resolveSlot(structure, overlay, slotId) ?: return emptyList()
        if (slot.setType != SetType.MyoRep || slot.isAutoGeneratedMyoMini()) return emptyList()
        val slots =
            LiveWorkoutOverlayOps.visibleSlotsForLift(structure, overlay, slot.workoutLiftId)
        val actIdx = slots.indexOfFirst { it.slotId == slotId }
        if (actIdx < 0) return emptyList()
        // Include minis under this slot and under match backoffs if this is a match activation.
        val targets = mutableListOf<SetSlotId>()
        targets += MyoMatchStructure.contiguousMinisAfter(slots, slot).map { it.slotId }
        if (MyoMatchStructure.isMyoMatchActivation(slots, actIdx)) {
            for (backoff in MyoMatchStructure.matchBackoffsAfter(slots, actIdx)) {
                targets += MyoMatchStructure.contiguousMinisAfter(slots, backoff).map { it.slotId }
            }
        }
        return targets
    }

    fun requiresMyoMiniDiscardConfirm(
        structure: WorkoutStructureProjection?,
        overlay: WorkoutOverlay,
        slotId: SetSlotId,
        newKind: LiveSetKind,
    ): Boolean =
        slotsDiscardedOnSetKindChange(structure, overlay, slotId, newKind).isNotEmpty()

    /**
     * Slots (minis + match backoffs) that will be removed when [slotId] changes to [newKind].
     * Does not include [slotId] itself. Used for Room cleanup and demote confirm.
     */
    fun slotsDiscardedOnSetKindChange(
        structure: WorkoutStructureProjection?,
        overlay: WorkoutOverlay,
        slotId: SetSlotId,
        newKind: LiveSetKind,
    ): List<SetSlotId> {
        val slot = LiveWorkoutOverlayOps.resolveSlot(structure, overlay, slotId) ?: return emptyList()
        val current = domainToLiveSetKind(slot.setType, slot.myoRepKind)
        if (current == newKind) return emptyList()
        val slots =
            LiveWorkoutOverlayOps.visibleSlotsForLift(structure, overlay, slot.workoutLiftId)
        val idx = slots.indexOfFirst { it.slotId == slotId }
        if (idx < 0) return emptyList()

        val targets = linkedSetOf<SetSlotId>()
        // Leaving match activation for any other kind: drop backoffs + minis.
        if (current == LiveSetKind.MyoRepMatch &&
            MyoMatchStructure.isMyoMatchActivation(slots, idx) &&
            newKind != LiveSetKind.MyoRepMatch
        ) {
            targets += MyoMatchStructure.matchBackoffsAfter(slots, idx).map { it.slotId }
            targets += MyoMatchStructure.contiguousMinisAfter(slots, slot).map { it.slotId }
            for (bo in MyoMatchStructure.matchBackoffsAfter(slots, idx)) {
                targets += MyoMatchStructure.contiguousMinisAfter(slots, bo).map { it.slotId }
            }
            return targets.toList()
        }
        // Floor demote or floor↔match: drop minis (and match backoffs when leaving match —
        // handled above). Floor → Match still drops floor minis.
        if (current.isMyo() && ( !newKind.isMyo() || current != newKind )) {
            targets += miniSlotsDiscardedOnDemote(structure, overlay, slotId)
        }
        return targets.toList()
    }

    /**
     * Applies [newKind] to [slotId], optionally discarding minis/match backoffs when demoting.
     * Promoting to Match materializes default match backoffs when none exist.
     * Returns null when the change is illegal (mini slot, invalid placement, unknown slot).
     */
    fun applySetKind(
        structure: WorkoutStructureProjection?,
        overlay: WorkoutOverlay,
        slotId: SetSlotId,
        newKind: LiveSetKind,
        scheme: ProgressionScheme,
        loadType: LoadType,
        liftDefaultRestSeconds: Int,
    ): WorkoutOverlay? {
        val current =
            LiveWorkoutOverlayOps.resolveSlot(structure, overlay, slotId) ?: return null
        val slots =
            LiveWorkoutOverlayOps.visibleSlotsForLift(structure, overlay, current.workoutLiftId)
        val setIndex = slots.indexOfFirst { it.slotId == slotId }
        val legal =
            setIndex >= 0 &&
                !current.isAutoGeneratedMyoMini() &&
                canSelectSetKind(slots, setIndex, newKind, scheme, loadType)
        if (!legal) return null

        val currentKind = domainToLiveSetKind(current.setType, current.myoRepKind)
        if (currentKind == newKind) return overlay

        var next = overlay

        // Leaving match activation: drop match backoffs + all minis in the block.
        if (currentKind == LiveSetKind.MyoRepMatch &&
            MyoMatchStructure.isMyoMatchActivation(slots, setIndex) &&
            newKind != LiveSetKind.MyoRepMatch
        ) {
            val cascade = LiveIntensifierOverlayOps.cascadeDeleteTargets(structure, next, slotId)
                .filter { it != slotId }
            for (id in cascade) {
                next =
                    next
                        .copy(loggedSets = next.loggedSets - id)
                        .apply(StructuralMutation.DeleteSet(id))
            }
        } else if (currentKind.isMyo() && !newKind.isMyo()) {
            // Floor demote: minis only.
            val minis = miniSlotsDiscardedOnDemote(structure, overlay, slotId)
            for (miniId in minis) {
                next =
                    next
                        .copy(loggedSets = next.loggedSets - miniId)
                        .apply(StructuralMutation.DeleteSet(miniId))
            }
        } else if (currentKind.isMyo() && newKind.isMyo() && currentKind != newKind) {
            // Floor ↔ Match: discard minis (do not keep floor minis as match minis).
            val minis = miniSlotsDiscardedOnDemote(structure, overlay, slotId)
            for (miniId in minis) {
                next =
                    next
                        .copy(loggedSets = next.loggedSets - miniId)
                        .apply(StructuralMutation.DeleteSet(miniId))
            }
            // Match → Floor: also strip match backoffs.
            if (currentKind == LiveSetKind.MyoRepMatch &&
                MyoMatchStructure.isMyoMatchActivation(slots, setIndex)
            ) {
                val backoffs = MyoMatchStructure.matchBackoffsAfter(slots, setIndex)
                for (bo in backoffs) {
                    next =
                        next
                            .copy(loggedSets = next.loggedSets - bo.slotId)
                            .apply(StructuralMutation.DeleteSet(bo.slotId))
                }
            }
        }

        val shape = shapeForKind(current, setIndex, newKind)
        next =
            next.copy(
                slotShapeOverrides = next.slotShapeOverrides + (slotId to shape),
                addedSlots =
                    next.addedSlots.map { added ->
                        if (added.slotId == slotId) {
                            added.copy(
                                setType = shape.setType,
                                myoRepKind = shape.myoRepKind,
                                isTopSet = shape.isTopSet,
                                repMin = shape.repMin,
                                repMax = shape.repMax,
                                rirGoal = shape.rirGoal,
                            )
                        } else {
                            added
                        }
                    },
            )

        // Entering Match with no backoffs → materialize default count as overlay adds.
        if (newKind == LiveSetKind.MyoRepMatch && currentKind != LiveSetKind.MyoRepMatch) {
            val afterShape =
                LiveWorkoutOverlayOps.visibleSlotsForLift(structure, next, current.workoutLiftId)
            val actIdx = afterShape.indexOfFirst { it.slotId == slotId }
            val existingBackoffs =
                if (actIdx >= 0) {
                    MyoMatchStructure.matchBackoffsAfter(afterShape, actIdx)
                } else {
                    emptyList()
                }
            if (existingBackoffs.isEmpty() && actIdx >= 0) {
                val activation = afterShape[actIdx]
                var afterId = slotId
                repeat(MyoRepLifecycle.DEFAULT_MATCH_BACKOFF_COUNT) {
                    val backoff = matchBackoffSlot(
                        after = activation,
                        position = activation.position + it + 1,
                        liftDefaultRestSeconds = liftDefaultRestSeconds,
                    )
                    next =
                        next.apply(
                            StructuralMutation.AddSet(afterSlotId = afterId, newSlot = backoff),
                        )
                    afterId = backoff.slotId
                }
            }
        }

        // Re-default rests for the whole lift after the type graph changes.
        // Auto minis stay at mini rest (never rewritten to main rest).
        val shapedSlots =
            LiveWorkoutOverlayOps.visibleSlotsForLift(structure, next, current.workoutLiftId)
        val types = shapedSlots.map { it.setType }
        val kinds = shapedSlots.map { it.myoRepKind }
        val miniFlags = shapedSlots.map { it.isAutoGeneratedMyoMini() }
        val rests =
            RestDefaultForTransition.redefaultAll(
                setTypes = types,
                liftDefaultRestSeconds = liftDefaultRestSeconds,
                myoKinds = kinds,
                isMyoMini = miniFlags,
            )
        val restMap = next.restSecondsOverrides.toMutableMap()
        shapedSlots.forEachIndexed { index, shaped ->
            restMap[shaped.slotId] = rests.getOrElse(index) { liftDefaultRestSeconds }
        }
        return next.copy(restSecondsOverrides = restMap)
    }

    private fun matchBackoffSlot(
        after: SetSlot,
        position: Int,
        liftDefaultRestSeconds: Int,
    ): SetSlot =
        SetSlot(
            slotId = SetSlotId.Overlay(
                OverlaySetInstanceId(
                    "match-bo-${slotIdKey(after.slotId)}-${UUID.randomUUID().toString().take(8)}",
                ),
            ),
            workoutLiftId = after.workoutLiftId,
            liftId = after.liftId,
            position = position,
            setType = SetType.MyoRep,
            isTopSet = false,
            repMin = 0,
            repMax = 0,
            rirGoal = if (after.rirGoal > 0) after.rirGoal else 1,
            restSeconds = liftDefaultRestSeconds,
            myoRepKind = MyoRepKind.RepMatching,
        )

    private fun slotIdKey(id: SetSlotId): String = when (id) {
        is SetSlotId.Template -> id.liftSetId.value
        is SetSlotId.Overlay -> id.instanceId.value
    }

    private fun shapeForKind(
        current: SetSlot,
        setIndex: Int,
        newKind: LiveSetKind,
    ): SlotShapeOverride =
        when (newKind) {
            LiveSetKind.Standard ->
                SlotShapeOverride(
                    setType = SetType.Standard,
                    myoRepKind = null,
                    isTopSet = current.isTopSet,
                    repMin = current.repMin,
                    repMax = current.repMax,
                    rirGoal = current.rirGoal,
                )
            LiveSetKind.DropSet ->
                SlotShapeOverride(
                    setType = SetType.DropSet,
                    myoRepKind = null,
                    isTopSet = false,
                    repMin = 0,
                    repMax = 0,
                    rirGoal = 0,
                )
            LiveSetKind.MyoRepFloor, LiveSetKind.MyoRepMatch ->
                SlotShapeOverride(
                    setType = SetType.MyoRep,
                    myoRepKind = newKind.toMyoRepKind(),
                    isTopSet = setIndex == 0 || current.isTopSet,
                    repMin =
                        if (current.repMin <= 0 && setIndex == 0) 8 else current.repMin,
                    repMax =
                        if (current.repMax <= 0 && setIndex == 0) 12 else current.repMax,
                    rirGoal = if (current.rirGoal <= 0) 1 else current.rirGoal,
                )
        }
}
