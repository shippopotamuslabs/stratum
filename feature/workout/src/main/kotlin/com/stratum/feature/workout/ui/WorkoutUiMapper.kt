/**
 * Maps the domain [RenderedWorkout] → presentation [WorkoutUiState.Loaded]. No domain
 * types are embedded in the presentation model (Detekt `ForbiddenDomainTypeInUiState`).
 *
 * Loading modality ([LoadType]) shapes the presentation copy without leaking the domain
 * enum: bodyweight lifts hide the weight column; assisted lifts display weights as their
 * absolute value (the user types a positive assistance amount; the ViewModel negates it
 * before persisting); weighted lifts are unchanged.
 *
 * Weight amounts on the presentation model are expressed in [displayUnit].
 * Live logging **persists Lb** (canonical storage); the ViewModel converts display → Lb on commit.
 */
internal object WorkoutUiMapper {
    fun map(
        rendered: RenderedWorkout,
        sessionStartedAtEpochMilli: Long,
        hasIncompleteLifts: Boolean = false,
        hasDirtyEdits: Boolean = false,
        imageUrlByLiftId: Map<String, String?> = emptyMap(),
        displayUnit: Weight.WeightUnit = Weight.WeightUnit.Lb,
        displayUnitEpoch: Int = 0,
        /** Lift id → catalog/default inter-set rest (seconds) for myo cluster exit. */
        defaultRestSecondsByLiftId: Map<String, Int> = emptyMap(),
    ): WorkoutUiState.Loaded {
        val lifts = rendered.lifts.map { lift ->
            val showWeightColumn = lift.loadType != LoadType.Bodyweight
            val weightHeaderLabel = when (lift.loadType) {
                LoadType.Bodyweight -> ""
                LoadType.Assisted -> "Assist"
                LoadType.Weighted -> "Weight"
            }
            val assistMode = lift.loadType == LoadType.Assisted
            val liftDefaultRest =
                defaultRestSecondsByLiftId[lift.liftId.value]
                    ?.coerceAtLeast(0)
                    ?: DEFAULT_LIFT_SET_REST_SECONDS
            val isPlateLoaded = lift.isPlateLoaded
            val isDoubleSided = lift.isDoubleSided
            val unitLabel = when (displayUnit) {
                Weight.WeightUnit.Lb -> "lb"
                Weight.WeightUnit.Kg -> "kg"
            }
            RenderedLiftUi(
                workoutLiftId = lift.workoutLiftId.value,
                liftId = lift.liftId.value,
                liftName = lift.liftName,
                showWeightColumn = showWeightColumn,
                weightHeaderLabel = weightHeaderLabel,
                useRestTimerBetweenLifts = lift.useRestTimerBetweenLifts,
                imageUrl = imageUrlByLiftId[lift.liftId.value],
                navigatorInitials = liftNavigatorInitials(lift.liftName),
                defaultRestSeconds = liftDefaultRest,
                workoutPinnedNotes = lift.workoutPinnedNotes,
                liftPinnedNotes = lift.liftPinnedNotes,
                isPlateLoaded = isPlateLoaded,
                isDoubleSided = isDoubleSided,
                unitLabel = unitLabel,
                sets = lift.sets.mapIndexed { setIndex, set ->
                    val prevLabel =
                        previousPerformanceLabel(
                            previousWeight = set.previousWeight,
                            previousReps = set.previousReps,
                            previousPartialReps = set.previousPartialReps,
                            showWeightColumn = showWeightColumn,
                            displayUnit = displayUnit,
                            assistMode = assistMode,
                        )
                    val prevRirLabel =
                        previousRirCaption(
                            previousRir = set.previousRir,
                            previousWeight = set.previousWeight,
                            previousReps = set.previousReps,
                            showWeightColumn = showWeightColumn,
                        )

                    // Domain recs are in the recommended weight's unit (live path: Lb).
                    val recSourceUnit = set.recommendedWeight.unit
                    val recommendedWeightAmount =
                        WeightConversion.convertAmount(
                            if (assistMode) abs(set.recommendedWeight.amount)
                            else set.recommendedWeight.amount,
                            recSourceUnit,
                            displayUnit,
                        )
                    val recommendedWeightLabel =
                        if (!showWeightColumn) {
                            ""
                        } else {
                            formatWeightAmountForDisplay(
                                amount = set.recommendedWeight.amount,
                                sourceUnit = recSourceUnit,
                                displayUnit = displayUnit,
                                assistMode = assistMode,
                            )
                        }

                    // Show a concrete rep count when either (a) a live overlay
                    // recommendation projected the next-set reps from the most recent
                    // performed set (D4), or (b) the snapshot baseline carries a prior
                    // performed set's reps, or (c) it was projected via straight-sets/fatigue decay.
                    // Otherwise fall back to the rep-range label for top sets, or blank for
                    // RIR-only backoff slots with no history (repMin=repMax=0 → domain
                    // cold-starts at 0, same as weight amount 0 → blank placeholder).
                    val showConcreteReps = set.recommendedReps > 0 &&
                        (set.hasLiveRepsRecommendation || set.previousReps != null || set.isProjected)

                    val recommendedRepsLabel = if (showConcreteReps) {
                        set.recommendedReps.toString()
                    } else {
                        if (set.repMin == 0 && set.repMax == 0) "" else "${set.repMin}-${set.repMax}"
                    }

                    val loggedDisplayAmount = set.loggedValue?.let { logged ->
                        WeightConversion.convertAmount(
                            if (assistMode) abs(logged.weight.amount) else logged.weight.amount,
                            logged.weight.unit,
                            displayUnit,
                        )
                    }

                    val slotAsSetSlot = set.toSetSlot()
                    val liftSlots = lift.sets.map { it.toSetSlot() }
                    val isMatchBackoff =
                        MyoMatchStructure.isMyoMatchBackoff(liftSlots, setIndex)
                    val canChange =
                        !slotAsSetSlot.isAutoGeneratedMyoMini() && !isMatchBackoff
                    val setKind = toWorkoutSetKind(set.setType, set.myoRepKind)
                    val allowed =
                        if (!canChange) {
                            emptyList()
                        } else {
                            LiveSetKind.entries
                                .filter { kind ->
                                    LiveSetTypeOverlayOps.canSelectSetKind(
                                        slots = liftSlots,
                                        setIndex = setIndex,
                                        kind = kind,
                                        scheme = lift.progressionScheme,
                                        loadType = lift.loadType,
                                    )
                                }
                                .map { it.toWorkoutSetKind() }
                        }
                    val hasDiscardableStructure =
                        canChange &&
                            set.setType == SetType.MyoRep &&
                            hasDiscardableMyoStructure(liftSlots, setIndex, slotAsSetSlot)

                    RenderedSetUi(
                        slotKey = slotKey(set.slotId),
                        positionLabel = (set.position + 1).toString(),
                        // Chip letter for the Set column (matches Edit Workout: S / M / MM / D).
                        setTypeLabel = setTypeChipLabel(set),
                        setKind = setKind,
                        allowedSetKinds = allowed,
                        canChangeSetType = canChange,
                        hasGeneratedMyoMinis = hasDiscardableStructure,
                        repRangeLabel = if (set.repMin == 0 && set.repMax == 0) null else "${set.repMin}–${set.repMax}",
                        rirLabel = "RIR ${set.rirGoal}",
                        recommendedWeightLabel = recommendedWeightLabel,
                        recommendedRepsLabel = recommendedRepsLabel,
                        loggedWeightLabel = loggedDisplayAmount?.let {
                            if (!showWeightColumn) "" else formatWeightAmount(it)
                        },
                        loggedRepsLabel = set.loggedValue?.reps?.toString(),
                        loggedWeightAmount = loggedDisplayAmount,
                        loggedReps = set.loggedValue?.reps,
                        loggedPartialReps = set.loggedValue?.partialReps,
                        isComplete = set.loggedValue != null,
                        previousWeightLabel = prevLabel,
                        previousRirLabel = prevRirLabel,
                        rirGoal = set.rirGoal,
                        repMin = set.repMin,
                        repMax = set.repMax,
                        recommendedWeightAmount = recommendedWeightAmount,
                        recommendedReps = set.recommendedReps,
                        hasLiveRepsRecommendation = set.hasLiveRepsRecommendation,
                        isProjected = set.isProjected,
                        loggedRir = set.loggedValue?.rir,
                        showWeightInput = showWeightColumn,
                        assistMode = assistMode,
                        restSeconds = set.restSeconds,
                        isPlateLoaded = isPlateLoaded,
                        isDoubleSided = isDoubleSided,
                        unitLabel = unitLabel,
                    )
                },
                supersetGroupId = lift.supersetGroupId?.value,
            )
        }
        return WorkoutUiState.Loaded(
            workoutId = rendered.workoutId.value,
            workoutName = rendered.workoutName,
            lifts = lifts,
            isFinalizing = false,
            sessionStartedAtEpochMilli = sessionStartedAtEpochMilli,
            hasIncompleteLifts = hasIncompleteLifts,
            hasDirtyEdits = hasDirtyEdits,
            displayUnitEpoch = displayUnitEpoch,
        )
    }

    private fun slotKey(slotId: SetSlotId): String = when (slotId) {
        is SetSlotId.Template -> slotId.liftSetId.value
        is SetSlotId.Overlay -> slotId.instanceId.value
    }

    /** Prev column: bodyweight is reps-only; weighted/assisted keep `weight × reps`. */
    private fun previousPerformanceLabel(
        previousWeight: Weight?,
        previousReps: Int?,
        previousPartialReps: Int?,
        showWeightColumn: Boolean,
        displayUnit: Weight.WeightUnit,
        assistMode: Boolean,
    ): String {
        if (previousReps == null) return "—"
        val repsLabel = formatRepsWithPartials(previousReps, previousPartialReps)
        if (!showWeightColumn) return repsLabel
        val weight = previousWeight ?: return "—"
        val displayWeight =
            formatWeightForDisplay(
                weight = weight,
                displayUnit = displayUnit,
                assistMode = assistMode,
                includeUnit = true,
            )
        return "$displayWeight × $repsLabel"
    }

    /** Prior RIR only when there is a prior performance to anchor it. */
    private fun previousRirCaption(
        previousRir: Int?,
        previousWeight: Weight?,
        previousReps: Int?,
        showWeightColumn: Boolean,
    ): String? {
        if (previousRir == null || previousReps == null) return null
        if (showWeightColumn && previousWeight == null) return null
        return "$previousRir RIR"
    }

    /** Set-column chip text — same vocabulary as template Edit Workout badges. */
    internal fun setTypeChipLabel(set: RenderedSet): String =
        when (set.setType) {
            SetType.DropSet -> "D"
            SetType.MyoRep ->
                when (set.myoRepKind) {
                    MyoRepKind.RepMatching -> "MM"
                    MyoRepKind.RepFloor, null -> "M"
                }
            SetType.Standard -> "S"
        }

    private fun toWorkoutSetKind(setType: SetType, myoRepKind: MyoRepKind?): WorkoutSetKind =
        when (setType) {
            SetType.Standard -> WorkoutSetKind.Standard
            SetType.DropSet -> WorkoutSetKind.DropSet
            SetType.MyoRep ->
                when (myoRepKind) {
                    MyoRepKind.RepMatching -> WorkoutSetKind.MyoRepMatch
                    MyoRepKind.RepFloor, null -> WorkoutSetKind.MyoRepFloor
                }
        }

    private fun LiveSetKind.toWorkoutSetKind(): WorkoutSetKind =
        when (this) {
            LiveSetKind.Standard -> WorkoutSetKind.Standard
            LiveSetKind.MyoRepFloor -> WorkoutSetKind.MyoRepFloor
            LiveSetKind.MyoRepMatch -> WorkoutSetKind.MyoRepMatch
            LiveSetKind.DropSet -> WorkoutSetKind.DropSet
        }

    private fun RenderedSet.toSetSlot(): SetSlot =
        SetSlot(
            slotId = slotId,
            workoutLiftId = workoutLiftId,
            liftId = liftId,
            position = position,
            setType = setType,
            isTopSet = isTopSet,
            repMin = repMin,
            repMax = repMax,
            rirGoal = rirGoal,
            restSeconds = restSeconds,
            myoRepKind = myoRepKind,
        )

    /** Cluster-scoped: match backoffs and/or minis under this activation/backoff. */
    private fun hasDiscardableMyoStructure(
        liftSlots: List<SetSlot>,
        setIndex: Int,
        slot: SetSlot,
    ): Boolean {
        if (slot.isAutoGeneratedMyoMini()) return false
        if (MyoMatchStructure.isMyoMatchActivation(liftSlots, setIndex) &&
            MyoMatchStructure.matchBackoffsAfter(liftSlots, setIndex).isNotEmpty()
        ) {
            return true
        }
        if (MyoMatchStructure.contiguousMinisAfter(liftSlots, slot).isNotEmpty()) return true
        if (!MyoMatchStructure.isMyoMatchActivation(liftSlots, setIndex)) return false
        return MyoMatchStructure.matchBackoffsAfter(liftSlots, setIndex).any { bo ->
            MyoMatchStructure.contiguousMinisAfter(liftSlots, bo).isNotEmpty()
        }
    }

    /**
     * Navigator initials: first letter of first two words, or first two letters of one word.
     * Non-letter characters are ignored within each word token.
     */
    internal fun liftNavigatorInitials(name: String): String {
        val words = name.trim().split(Regex("\\s+")).filter { it.isNotEmpty() }
        if (words.isEmpty()) return ""
        return if (words.size == 1) {
            words[0].filter { it.isLetterOrDigit() }.take(2).uppercase()
        } else {
            buildString {
                words.take(2).forEach { word ->
                    val ch = word.firstOrNull { it.isLetterOrDigit() }
                    if (ch != null) append(ch.uppercaseChar())
                }
            }
        }
    }
}
