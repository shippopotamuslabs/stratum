/** Set log/structure mutators for [LiveWorkoutSessionRuntime]. */

internal suspend fun LiveWorkoutSessionRuntime.handleLogSet(cmd: SessionCommand.LogSet) {
    val session = cachedSessionId ?: return
    val slot = resolveSlotByKey(cmd.slotKey) ?: return
    val slotId = slot.slotId
    val loadType = liftsById[slot.liftId]?.loadType ?: LoadType.Weighted
    val normalizedWeight =
        storageWeightFromDisplay(
            displayAmount = cmd.weight.amount,
            displayUnit = cmd.weight.unit,
            loadType = loadType,
        )

    val wasAlreadyLogged = slotId in overlay.loggedSets
    val normalizedPartials = cmd.partialReps.normalizedPartialReps()
    val persistedId =
        persistLoggedSet(
            session = session,
            slot = slot,
            weight = normalizedWeight,
            reps = cmd.reps,
            rir = cmd.rir,
            partialReps = normalizedPartials,
        )
    if (persistedId == null) {
        effects.emitEvent(WorkoutUiEvent.SetLogFailed(slotKey = cmd.slotKey))
        return
    }

    var next =
        overlay.copy(
            loggedSets =
                overlay.loggedSets +
                    (
                        slotId to
                            LoggedSetValue(
                                slotId = slotId,
                                weight = normalizedWeight,
                                reps = cmd.reps,
                                rir = cmd.rir,
                                partialReps = normalizedPartials,
                                persistedLoggedSetId = persistedId.value,
                            )
                    ),
        )
    next =
        LiveIntensifierOverlayOps.applyMyoLifecycleAfterLog(
            structure = structure,
            overlay = next,
            loggedSlotId = slotId,
        )
    commitOverlay(next)
    // Mini/backoff insert renumbers later slots — rewrite Room setIndex before any next log.
    reindexRoomSetIndicesForLift(session, slot.workoutLiftId)
    // Recompute before flush so DataStore keeps the post-log live recs. Restore must see
    // the frozen block weights; flushing pre-recompute left recs empty/stale and a reopen
    // re-ran last-set floor Reduce (e.g. remaining 315 → 295).
    recomputeRecommendations()
    flushOverlay()
    render()
    if (wasAlreadyLogged) {
        effects.emitEvent(WorkoutUiEvent.SetAmended(slotKey = cmd.slotKey))
    } else {
        // Fully resolve rest here (post-lifecycle) so Compose never re-guesses from stale lists.
        val ordered = visibleSlotsForLift(slot.workoutLiftId)
        val idx = ordered.indexOfFirst { it.slotId == slotId }
        val loggedSlot = ordered.getOrNull(idx) ?: slot
        val nextSlot = ordered.getOrNull(idx + 1)
        val liftDefault =
            liftsById[slot.liftId]?.resolvedDefaultRestSeconds()
                ?: LiveWorkoutSessionRuntime.DEFAULT_LIFT_REST_SECONDS
        val rendered = merge()
        val renderedLift =
            rendered.lifts.firstOrNull { it.workoutLiftId == slot.workoutLiftId }
        val groupId = renderedLift?.supersetGroupId
        val isSupersetMember = groupId != null
        val isLastInChain =
            when {
                groupId == null || renderedLift == null -> true
                else ->
                    rendered.lifts
                        .filter { it.supersetGroupId == groupId }
                        .lastOrNull()
                        ?.workoutLiftId == renderedLift.workoutLiftId
            }
        val fullyComplete =
            rendered.lifts.isNotEmpty() &&
                rendered.lifts.all { lift -> lift.sets.all { it.loggedValue != null } }
        val restSeconds =
            restSecondsAfterLoggingSet(
                setRestSeconds = loggedSlot.restSeconds,
                isSupersetMember = isSupersetMember,
                useRestTimerBetweenLifts = renderedLift?.useRestTimerBetweenLifts == true,
                isLastInSupersetChain = isLastInChain,
                workoutFullyComplete = fullyComplete,
                isMyoSet = loggedSlot.setType == SetType.MyoRep,
                isMyoMini = loggedSlot.isAutoGeneratedMyoMini(),
                myoRepKind = loggedSlot.myoRepKind,
                nextIsMyoMini = nextSlot?.isAutoGeneratedMyoMini() == true,
                nextIsDropSet = nextSlot?.setType == SetType.DropSet,
                liftDefaultRestSeconds = liftDefault,
            )
        effects.emitEvent(
            WorkoutUiEvent.SetLogged(
                slotKey = cmd.slotKey,
                restSeconds = restSeconds,
            ),
        )
    }
}

/**
 * Persists weight/reps/RIR for [slot]. Returns the durable Room [LoggedSetId] on success
 * (existing or newly inserted), or null on failure.
 */
internal suspend fun LiveWorkoutSessionRuntime.persistLoggedSet(
    session: TrainingSessionId,
    slot: SetSlot,
    weight: Weight,
    reps: Int,
    rir: Int?,
    partialReps: Int? = null,
): LoggedSetId? {
    val normalizedPartials = partialReps.normalizedPartialReps()
    val dbSet = findLoggedSetForSlot(session, slot)
    if (dbSet != null) {
        val updateResult =
            updateLoggedSet(
                dbSet.copy(
                    weight = weight,
                    reps = reps,
                    rir = rir,
                    partialReps = normalizedPartials,
                ),
            )
        if (updateResult.isFailure) {
            effects.publishUserMessage(LiveWorkoutSessionRuntime.MSG_LOG_SET_FAILED)
            return null
        }
        return dbSet.id
    }
    val insertResult =
        logSetUseCase(
            LogSetCommand(
                sessionId = session,
                liftId = slot.liftId,
                workoutLiftId = slot.workoutLiftId,
                setIndex = slot.position,
                weight = weight,
                reps = reps,
                rir = rir,
                completedAt = Instant.now(),
                // Session-only lifts (overlay add / ad-hoc) are not on the template yet;
                // stamp live slot shape so LoggedLiftContext is complete without a lookup.
                setType = slot.setType,
                repMin = slot.repMin,
                repMax = slot.repMax,
                rirGoal = slot.rirGoal,
                partialReps = normalizedPartials,
            ),
        )
    if (insertResult.isFailure) {
        effects.publishUserMessage(LiveWorkoutSessionRuntime.MSG_LOG_SET_FAILED)
        return null
    }
    return insertResult.getOrNull()?.id
}

/**
 * Resolves the Room row for [slot].
 * Prefer [LoggedSetValue.persistedLoggedSetId] (stable across renumber); fall back to
 * (workoutLiftId, setIndex) only for rows not already owned by another overlay slot.
 */
internal suspend fun LiveWorkoutSessionRuntime.findLoggedSetForSlot(
    session: TrainingSessionId,
    slot: SetSlot,
): LoggedSet? {
    val dbSets = getLoggedSetsForSession(session)
    val persistedId = overlay.loggedSets[slot.slotId]?.persistedLoggedSetId
    if (persistedId != null) {
        dbSets.firstOrNull { it.id.value == persistedId }?.let { return it }
    }
    val ownedByOtherSlot =
        overlay.loggedSets
            .filterKeys { it != slot.slotId }
            .values
            .mapNotNull { it.persistedLoggedSetId }
            .toSet()
    return dbSets.firstOrNull { row ->
        row.liftContext.workoutLiftId == slot.workoutLiftId &&
            row.setIndex == slot.position &&
            row.id.value !in ownedByOtherSlot
    }
}

/**
 * After structure renumber, rewrite Room [LoggedSet.setIndex] to current visible positions
 * using stable overlay ids so the next log cannot collide with a stale later-backoff index.
 */
internal suspend fun LiveWorkoutSessionRuntime.reindexRoomSetIndicesForLift(
    session: TrainingSessionId,
    workoutLiftId: WorkoutLiftId,
) {
    val ordered = visibleSlotsForLift(workoutLiftId)
    val dbSets =
        getLoggedSetsForSession(session).filter {
            it.liftContext.workoutLiftId == workoutLiftId
        }
    val updates =
        LiveWorkoutOverlayOps.roomSetIndexUpdates(
            orderedSlots = ordered,
            loggedSets = overlay.loggedSets,
            dbSets = dbSets,
        )
    for (updated in updates) {
        val result = updateLoggedSet(updated)
        if (result.isFailure) {
            effects.publishUserMessage(LiveWorkoutSessionRuntime.MSG_LOG_SET_FAILED)
            return
        }
    }
}

internal suspend fun LiveWorkoutSessionRuntime.handleUnlogSet(cmd: SessionCommand.UnlogSet) {
    val session = cachedSessionId ?: return
    val slot = resolveSlotByKey(cmd.slotKey) ?: return
    val slotId = slot.slotId
    // Match activation clears all minis under its backoffs (not just contiguous after act).
    // Floor / match backoff: self + contiguous minis. Backoff rows stay on unlog.
    val cascade =
        LiveIntensifierOverlayOps.unlogCascadeTargets(structure, overlay, slotId)
    for (targetId in cascade.logTargets) {
        val targetSlot = resolveSlot(targetId) ?: continue
        val dbSet = findLoggedSetForSlot(session, targetSlot)
        if (dbSet != null) {
            val deleteResult = deleteLoggedSet(dbSet.id)
            if (deleteResult.isFailure) {
                effects.publishUserMessage(LiveWorkoutSessionRuntime.MSG_UNLOG_SET_FAILED)
                return
            }
        }
    }
    var next = overlay.copy(loggedSets = overlay.loggedSets - cascade.logTargets.toSet())
    for (miniId in cascade.minisToDelete) {
        next = next.apply(StructuralMutation.DeleteSet(miniId))
    }
    commitOverlay(next)
    reindexRoomSetIndicesForLift(session, slot.workoutLiftId)
    recomputeRecommendations()
    render()
    flushOverlay()
}

internal suspend fun LiveWorkoutSessionRuntime.handleAddSet(cmd: SessionCommand.AddSet) {
    val anchor = resolveSlot(cmd.afterSlotId) ?: return
    val newPosition = anchor.position + 1
    // Always append a Standard working set — never inherit Myo/Drop type without kind.
    val liftDefaultRest =
        liftsById[anchor.liftId]?.resolvedDefaultRestSeconds()
            ?: LiveWorkoutSessionRuntime.DEFAULT_LIFT_REST_SECONDS
    val added =
        SetSlot(
            slotId =
                SetSlotId.Overlay(
                    OverlaySetInstanceId("added-${overlay.addedSlots.size + 1}"),
                ),
            workoutLiftId = anchor.workoutLiftId,
            liftId = anchor.liftId,
            position = newPosition,
            setType = SetType.Standard,
            isTopSet = false,
            repMin = 0,
            repMax = 0,
            rirGoal = if (anchor.rirGoal > 0) anchor.rirGoal else 2,
            restSeconds = liftDefaultRest,
            myoRepKind = null,
        )
    val baseline = snapshotBySlot[cmd.afterSlotId]
    val fatigue = fatigueByLiftId[anchor.liftId] ?: FatigueDecay(null, null)
    val coldWeight = Weight(0.0, Weight.WeightUnit.Lb)
    val estimatedReps =
        estimateAddedSetReps(
            previousRecommendation =
                baseline ?: SlotRecommendation(cmd.afterSlotId, coldWeight, anchor.repMin),
            nextSetIndex = newPosition,
            perLiftSlope = fatigue.slope,
            perLiftIntercept = fatigue.intercept,
        )
    val addedWeight = baseline?.recommendedWeight ?: coldWeight
    val addedRecommendation =
        SlotRecommendation(added.slotId, addedWeight, estimatedReps)
    commitOverlay(
        overlay
            .apply(StructuralMutation.AddSet(afterSlotId = cmd.afterSlotId, newSlot = added))
            .copy(
                dynamicBaselines =
                    overlay.dynamicBaselines + (added.slotId to addedRecommendation),
            ),
    )
    cachedSessionId?.let { reindexRoomSetIndicesForLift(it, anchor.workoutLiftId) }
    recomputeRecommendations()
    render()
    flushOverlay()
}

internal suspend fun LiveWorkoutSessionRuntime.handleAddSetForLift(cmd: SessionCommand.AddSetForLift) {
    val lastSlot =
        visibleSlotsForLift(WorkoutLiftId(cmd.workoutLiftId)).maxByOrNull { it.position }
            ?: return
    handleAddSet(SessionCommand.AddSet(afterSlotId = lastSlot.slotId))
}

internal suspend fun LiveWorkoutSessionRuntime.handleDeleteSet(cmd: SessionCommand.DeleteSet) {
    // DeleteSet also drops restSecondsOverrides[slotId] (domain apply). Undo does not
    // restore rest overrides — they are not on the undo stack.
    commitOverlay(overlay.apply(StructuralMutation.DeleteSet(cmd.slotId)))
    recomputeRecommendations()
    render()
    flushOverlay()
}

internal suspend fun LiveWorkoutSessionRuntime.handleDeleteSetByKey(cmd: SessionCommand.DeleteSetByKey) {
    val slot = resolveSlotByKey(cmd.slotKey) ?: return
    val remainingForLift = visibleSlotsForLift(slot.workoutLiftId)
    if (remainingForLift.size <= 1) return

    // Always cascade (match activation → backoffs + minis; floor → minis; drop → chain).
    // UI previously only deleted the single row, leaving orphan match backoffs / minis.
    val targets =
        LiveIntensifierOverlayOps.cascadeDeleteTargets(structure, overlay, slot.slotId)
    // Do not delete every remaining set of the lift — keep at least one row.
    val remainingAfter = remainingForLift.count { it.slotId !in targets.toSet() }
    if (remainingAfter < 1) return

    val session = cachedSessionId
    if (session != null) {
        for (id in targets) {
            val targetSlot = resolveSlot(id) ?: continue
            val dbSet = findLoggedSetForSlot(session, targetSlot)
            if (dbSet != null) {
                val deleteResult = deleteLoggedSet(dbSet.id)
                if (deleteResult.isFailure) {
                    effects.publishUserMessage(LiveWorkoutSessionRuntime.MSG_UNLOG_SET_FAILED)
                    return
                }
            }
        }
    }
    val workoutLiftId = slot.workoutLiftId
    var next = overlay
    for (id in targets) {
        next =
            next.copy(loggedSets = next.loggedSets - id)
                .apply(StructuralMutation.DeleteSet(id))
    }
    commitOverlay(next)
    session?.let { reindexRoomSetIndicesForLift(it, workoutLiftId) }
    recomputeRecommendations()
    render()
    flushOverlay()
}

internal suspend fun LiveWorkoutSessionRuntime.handleUndo() {
    commitOverlay(overlay.undo())
    recomputeRecommendations()
    render()
    flushOverlay()
}

